const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1100},acceptDownloads:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.BASE_URL||'http://127.0.0.1:8765',{waitUntil:'networkidle'});
 await page.clock.install();
 assert.equal(await page.locator('#hr-value').innerText(),'—');
 assert.equal(await page.locator('#scene-toggle').isChecked(),false);
 await page.getByRole('button',{name:'Try synthetic signal'}).click();
 assert.match(await page.locator('#source-badge').innerText(),/SYNTHETIC/);
 assert.ok(Number(await page.locator('#hr-value').innerText())>65);
 await page.locator('#freeze').check();
 const frozen=await page.locator('#ppg-trace').evaluate(c=>c.toDataURL());
 await page.clock.runFor(2000);
 assert.equal(await page.locator('#ppg-trace').evaluate(c=>c.toDataURL()),frozen);
 await page.locator('#freeze').uncheck();
 await page.getByRole('button',{name:'Record session',exact:true}).click();
 assert.equal(await page.locator('#hr-value').innerText(),'—');
 await page.clock.runFor(14000);
 await page.getByRole('button',{name:'Add sync marker'}).click();
 await page.getByRole('button',{name:'Stop recording',exact:true}).click();
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON'}).click();
 const file=await downloaded;const recording=JSON.parse(fs.readFileSync(await file.path(),'utf8'));
 assert.equal(recording.source,'synthetic');assert.ok(recording.frames.length>350);assert.ok(recording.beats.length>3);assert.ok(recording.waveform.length>100);assert.equal(recording.markers.length,1);assert.ok(recording.reference.beats.length>10);
 fs.mkdirSync('benchmarks/artifacts',{recursive:true});
 fs.writeFileSync('benchmarks/artifacts/synthetic-session.json',JSON.stringify(recording));
 await page.screenshot({path:'benchmarks/artifacts/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'benchmarks/artifacts/mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Stop',exact:true}).click();
 assert.equal(await page.locator('#hr-value').innerText(),'—');assert.equal(await page.locator('#ibi-value').innerText(),'—');
 assert.equal(await page.locator('#record-button').isDisabled(),true);
 const diagnosticDownload=page.waitForEvent('download');await page.locator('#diagnostics-button').click();
 const diagnosticFile=await diagnosticDownload;const diagnostic=JSON.parse(fs.readFileSync(await diagnosticFile.path(),'utf8'));
 assert.equal(diagnostic.kind,'diagnostic');assert.ok(diagnostic.frames.length>350);assert.ok(diagnostic.events.some(e=>e.type==='stop'));
 assert.ok(diagnostic.frames.every(f=>!('image' in f)&&!('landmarks' in f)));
 fs.writeFileSync('benchmarks/artifacts/diagnostics.json',JSON.stringify(diagnostic));
 assert.deepEqual(errors,[]);
 await browser.close();
 // Fake camera verifies the browser capture lifecycle without accessing a person's camera.
 const cameraBrowser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL||'chrome',args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
 const cameraPage=await cameraBrowser.newPage();
 await cameraPage.route('**/face_mesh.js',route=>route.fulfill({contentType:'application/javascript',body:'window.FaceMesh=class{setOptions(){}onResults(f){this.callback=f}async initialize(){}async send(){this.callback({multiFaceLandmarks:[]})}}'}));
 await cameraPage.goto(process.env.BASE_URL||'http://127.0.0.1:8765');
 await cameraPage.locator('#camera-button').click();
 await cameraPage.waitForFunction(()=>document.getElementById('source-badge').textContent==='LIVE CAMERA');
 await cameraPage.waitForFunction(()=>document.getElementById('status-message').textContent.includes('Face missing'));
 assert.equal(await cameraPage.locator('#hr-value').innerText(),'—');
 await cameraPage.waitForFunction(()=>document.querySelectorAll('.capture-check').length===8);
 assert.match(await cameraPage.locator('#capture-advice').innerText(),/Center your face/);
 await cameraPage.setViewportSize({width:390,height:844});
 assert.equal(await cameraPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await cameraPage.screenshot({path:'benchmarks/artifacts/capture-feedback-mobile.png',fullPage:true});
 const track=await cameraPage.locator('#webcam').evaluateHandle(v=>v.srcObject.getVideoTracks()[0]);
 await cameraPage.locator('#stop-button').click();assert.equal(await track.evaluate(t=>t.readyState),'ended');
 await cameraBrowser.close();console.log('PASS browser: desktop/mobile, trace freeze, recording, export, stop/reset, fake-camera lifecycle.');
})().catch(e=>{console.error(e);process.exit(1)});
